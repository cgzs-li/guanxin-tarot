import { readFileSync, writeFileSync, mkdirSync, cpSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = readFileSync(resolve(root, 'index.html'), 'utf8');
if (source.includes('window.GUANXIN_STATIC_PREVIEW=true;')) throw new Error('Workers needs the full source, not the Pages preview build');
const data = {};
for (const [name, count] of [['cardLibrary', 78], ['spreads', 25]]) {
  data[name] = JSON.parse(source.match(new RegExp('const ' + name + '=(\\[[\\s\\S]*?\\]);'))[1]);
  if (data[name].length !== count) throw new Error('Unexpected card or spread count');
}
data.SYSTEM_PROMPT = readFileSync(resolve(root, 'llm-backend/server.py'), 'utf8').match(/SYSTEM_PROMPT = """([\s\S]*?)"""/)[1];
mkdirSync(resolve(root, 'worker'), { recursive: true });
writeFileSync(resolve(root, 'worker/generated-library.js'), '// Generated by tools/build_workers.mjs; edit the original HTML data.\n' +
  Object.entries(data).map(([name, value]) => 'export const ' + name + '=' + JSON.stringify(value) + ';').join('\n') + '\n');
mkdirSync(resolve(root, 'public'), { recursive: true });
cpSync(resolve(root, 'index.html'), resolve(root, 'public/index.html'));
cpSync(resolve(root, 'assets'), resolve(root, 'public/assets'), { recursive: true });
console.log('Workers build: 78 cards, 25 spreads; public assets only, no private config.');
